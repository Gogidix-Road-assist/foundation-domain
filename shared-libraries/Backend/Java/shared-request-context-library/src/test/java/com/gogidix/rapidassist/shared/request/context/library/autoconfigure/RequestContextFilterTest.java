package com.gogidix.rapidassist.shared.request.context.library.autoconfigure;

import com.gogidix.rapidassist.shared.request.context.library.domain.RequestContext;
import com.gogidix.rapidassist.shared.request.context.library.domain.RequestContextHolder;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.web.servlet.WebMvcTest;
import org.springframework.context.annotation.Import;
import org.springframework.security.test.context.support.WithMockUser;
import org.springframework.test.context.TestPropertySource;
import org.springframework.test.web.servlet.MockMvc;

import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.*;

/**
 * Tests for RequestContextFilter.
 */
@WebMvcTest(controllers = com.gogidix.rapidassist.shared.request.context.library.web.TestController.class)
@Import({RequestContextFilter.class, RequestContextProperties.class, TestSecurityConfiguration.class})
class RequestContextFilterTest {

    @Autowired
    private MockMvc mockMvc;

    @Autowired
    private RequestContextProperties properties;

    @BeforeEach
    void setUp() {
        RequestContextHolder.clear();
    }

    @AfterEach
    void tearDown() {
        RequestContextHolder.clear();
    }

    @Test
    void shouldExtractContextFromHeaders() throws Exception {
        mockMvc.perform(get("/api/test/context")
                        .header("X-Tenant-Id", "tenant-123")
                        .header("X-User-Id", "user-456")
                        .header("X-Request-Id", "123e4567-e89b-12d3-a456-426614174000")
                        .header("X-Country", "US"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.status").value("context-found"))
                .andExpect(jsonPath("$.tenantId").value("tenant-123"))
                .andExpect(jsonPath("$.userId").value("user-456"))
                .andExpect(jsonPath("$.requestId").value("123e4567-e89b-12d3-a456-426614174000"))
                .andExpect(jsonPath("$.country").value("US"))
                .andExpect(jsonPath("$.correlationId").exists());
        // Context is automatically cleared by the filter's finally block after request completes
    }

    @Test
    void shouldGenerateCorrelationIdWhenNotProvided() throws Exception {
        mockMvc.perform(get("/api/test/context")
                        .header("X-Tenant-Id", "tenant-123"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.status").value("context-found"))
                .andExpect(jsonPath("$.correlationId").exists());
        // Correlation ID is generated by the filter and returned in the response
    }

    @Test
    void shouldHandleMissingOptionalHeaders() throws Exception {
        mockMvc.perform(get("/api/test/context")
                        .header("X-Tenant-Id", "tenant-123"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.status").value("context-found"))
                .andExpect(jsonPath("$.tenantId").value("tenant-123"))
                .andExpect(jsonPath("$.userId").isEmpty())
                .andExpect(jsonPath("$.requestId").isEmpty());
        // Optional headers are handled correctly when not provided
    }

    @Test
    void shouldReturnBadRequestWhenTenantIdMissing() throws Exception {
        mockMvc.perform(get("/api/test/context"))
                .andExpect(status().isBadRequest());
    }

    @Test
    void shouldValidateRequestIdFormat() throws Exception {
        mockMvc.perform(get("/api/test/context")
                        .header("X-Tenant-Id", "tenant-123")
                        .header("X-Request-Id", "invalid-uuid-format"))
                .andExpect(status().isBadRequest());
    }

    @Test
    void shouldAcceptValidRequestId() throws Exception {
        String validRequestId = UUID.randomUUID().toString();

        mockMvc.perform(get("/api/test/context")
                        .header("X-Tenant-Id", "tenant-123")
                        .header("X-Request-Id", validRequestId))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.requestId").value(validRequestId));
    }

    @Test
    void shouldClearContextAfterRequest() throws Exception {
        mockMvc.perform(get("/api/test/context")
                        .header("X-Tenant-Id", "tenant-123"))
                .andExpect(status().isOk());

        // Filter's finally block automatically clears context after request completes
        assertThat(RequestContextHolder.get().isEmpty()).isTrue();
    }

    @Test
    void shouldReturnCorrelationIdInResponse() throws Exception {
        String correlationId = UUID.randomUUID().toString();

        mockMvc.perform(get("/api/test/context")
                        .header("X-Tenant-Id", "tenant-123")
                        .header("X-Correlation-Id", correlationId))
                .andExpect(status().isOk())
                .andExpect(header().string("X-Correlation-Id", correlationId));
    }

    @Test
    void shouldHandleAllHeaders() throws Exception {
        mockMvc.perform(get("/api/test/context")
                        .header("X-Tenant-Id", "tenant-123")
                        .header("X-User-Id", "user-456")
                        .header("X-Request-Id", UUID.randomUUID().toString())
                        .header("X-Correlation-Id", UUID.randomUUID().toString())
                        .header("X-Country", "CA"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.status").value("context-found"))
                .andExpect(jsonPath("$.tenantId").value("tenant-123"))
                .andExpect(jsonPath("$.userId").value("user-456"))
                .andExpect(jsonPath("$.country").value("CA"));
    }

    @Test
    void shouldSupportCustomHeaderNames() throws Exception {
        properties.setTenantIdHeader("Custom-Tenant");
        properties.setUserIdHeader("Custom-User");
        properties.setRequestIdHeader("Custom-Request");

        mockMvc.perform(get("/api/test/context")
                        .header("Custom-Tenant", "tenant-123")
                        .header("Custom-User", "user-456")
                        .header("Custom-Request", UUID.randomUUID().toString()))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.status").value("context-found"))
                .andExpect(jsonPath("$.tenantId").value("tenant-123"))
                .andExpect(jsonPath("$.userId").value("user-456"));
    }

    @Test
    void shouldMakeTenantIdRequiredWhenConfigured() throws Exception {
        properties.setRequireTenantId(true);

        mockMvc.perform(get("/api/test/context"))
                .andExpect(status().isBadRequest());
    }

    @Test
    void shouldHandleEmptyTenantId() throws Exception {
        mockMvc.perform(get("/api/test/context")
                        .header("X-Tenant-Id", ""))
                .andExpect(status().isBadRequest());
    }

    @Test
    void shouldHandleWhitespaceTenantId() throws Exception {
        mockMvc.perform(get("/api/test/context")
                        .header("X-Tenant-Id", "   "))
                .andExpect(status().isBadRequest());
    }

    @Test
    void shouldPreserveTenantIdValue() throws Exception {
        mockMvc.perform(get("/api/test/context")
                        .header("X-Tenant-Id", "my-tenant-123"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.tenantId").value("my-tenant-123"));
    }

    @Test
    void shouldPreserveUserIdValue() throws Exception {
        mockMvc.perform(get("/api/test/context")
                        .header("X-Tenant-Id", "tenant-123")
                        .header("X-User-Id", "user-789"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.userId").value("user-789"));
    }
}
