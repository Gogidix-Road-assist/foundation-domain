package com.gogidix.rapidassist.ai.analytics.domain.model;

/**
 * Enum representing the type of chart visualization
 */
public enum ChartType {
    /**
     * Line chart
     */
    LINE,

    /**
     * Bar chart
     */
    BAR,

    /**
     * Pie chart
     */
    PIE,

    /**
     * Doughnut chart
     */
    DOUGHNUT,

    /**
     * Area chart
     */
    AREA,

    /**
     * Scatter plot
     */
    SCATTER,

    /**
     * Heatmap
     */
    HEATMAP,

    /**
     * Table
     */
    TABLE,

    /**
     * Metric card (single value)
     */
    METRIC_CARD,

    /**
     * Gauge chart
     */
    GAUGE
}
