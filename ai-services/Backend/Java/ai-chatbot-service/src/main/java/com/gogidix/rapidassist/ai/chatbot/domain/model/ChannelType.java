package com.gogidix.rapidassist.ai.chatbot.domain.model;

/**
 * Enumeration representing the communication channel through which the chatbot is accessed.
 */
public enum ChannelType {

    /**
     * Web-based chat interface
     */
    WEB,

    /**
     * Mobile application
     */
    MOBILE_APP,

    /**
     * SMS/text messaging
     */
    SMS,

    /**
     * Email channel
     */
    EMAIL,

    /**
     * Social media platform
     */
    SOCIAL_MEDIA,

    /**
     * Voice-based assistant
     */
    VOICE_ASSISTANT,

    /**
     * API integration
     */
    API,

    /**
     * In-person kiosk
     */
    KIOSK
}
