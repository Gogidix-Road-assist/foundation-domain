package com.gogidix.rapidassist.ai.summization.domain.model;

/**
 * Enumeration representing the style of summary to generate.
 */
public enum SummaryStyle {
    /**
     * Brief, concise summary
     */
    BRIEF,

    /**
     * Standard length summary
     */
    STANDARD,

    /**
     * Detailed, comprehensive summary
     */
    DETAILED,

    /**
     * Bullet point summary
     */
    BULLET,

    /**
     * Executive summary format
     */
    EXECUTIVE,

    /**
     * Technical summary format
     */
    TECHNICAL,

    /**
     * Simplified summary for general audience
     */
    SIMPLIFIED
}
