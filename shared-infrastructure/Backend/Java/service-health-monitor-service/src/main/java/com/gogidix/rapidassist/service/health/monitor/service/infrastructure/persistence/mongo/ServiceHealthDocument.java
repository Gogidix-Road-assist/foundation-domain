package com.gogidix.rapidassist.service.health.monitor.service.infrastructure.persistence.mongo;

import org.springframework.data.annotation.Id;
import org.springframework.data.mongodb.core.index.CompoundIndex;
import org.springframework.data.mongodb.core.index.Indexed;
import org.springframework.data.mongodb.core.mapping.Document;

import java.time.Instant;
import java.util.Map;

@Document(collection = "service_health")
@CompoundIndex(name = "tenant_service_checkedAt_idx", def = "{'tenantId': 1, 'serviceName': 1, 'checkedAt': -1}")
@CompoundIndex(name = "tenant_checkedAt_idx", def = "{'tenantId': 1, 'checkedAt': -1}")
public class ServiceHealthDocument {

    @Id
    private String id;

    @Indexed
    private String tenantId;

    @Indexed
    private String country;

    @Indexed
    private String serviceName;

    @Indexed
    private String instanceId;

    @Indexed
    private String status;

    @Indexed
    private Instant checkedAt;

    private Map<String, String> details;

    @Indexed(expireAfterSeconds = 0)
    private Instant expiresAt;

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getTenantId() {
        return tenantId;
    }

    public void setTenantId(String tenantId) {
        this.tenantId = tenantId;
    }

    public String getCountry() {
        return country;
    }

    public void setCountry(String country) {
        this.country = country;
    }

    public String getServiceName() {
        return serviceName;
    }

    public void setServiceName(String serviceName) {
        this.serviceName = serviceName;
    }

    public String getInstanceId() {
        return instanceId;
    }

    public void setInstanceId(String instanceId) {
        this.instanceId = instanceId;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public Instant getCheckedAt() {
        return checkedAt;
    }

    public void setCheckedAt(Instant checkedAt) {
        this.checkedAt = checkedAt;
    }

    public Map<String, String> getDetails() {
        return details;
    }

    public void setDetails(Map<String, String> details) {
        this.details = details;
    }

    public Instant getExpiresAt() {
        return expiresAt;
    }

    public void setExpiresAt(Instant expiresAt) {
        this.expiresAt = expiresAt;
    }
}
